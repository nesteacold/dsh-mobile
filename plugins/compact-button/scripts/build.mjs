import { readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
const root = new URL('../', import.meta.url)
const read = path => readFileSync(new URL(path, root), 'utf8')
export function buildClient() {
  const logic = read('lib/logic.mjs').replace(/^export /gm, '')
  const locales = Object.fromEntries(['en', 'vi'].map(lang => [lang, JSON.parse(read(`locale/${lang}.json`))]))
  return '// Generated by npm run build; edit src/client.js, lib/logic.mjs or locale/*.json.\n' +
    read('src/client.js').replace('/* LOGIC */', logic).replace('/* LOCALES */', JSON.stringify(locales))
}
if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  writeFileSync(new URL('lib/client.js', root), buildClient())
}
