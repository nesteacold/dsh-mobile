// Regenerate the lead-preset overrides in ../cordis.patch.yml from the INSTALLED DSH.
//
// Why: a Loader patch cannot insert into a preset's nested `delegation` group (presets are not
// `group: true` rows), so adding the role tools means overriding the whole preset config. A
// hand-copied override goes stale on every DSH update. This script re-copies the shipped
// `standard` and `cordis` (Creator) presets verbatim, inserts the four role tools into their
// `delegation` group, and rewrites the block between the GENERATED markers.
//
// Run with DSH's own Electron so files inside app.asar are readable:
//   $env:ELECTRON_RUN_AS_NODE=1; & "<DSH>\DeepSeek Harness.exe" sync-presets.cjs [--check]
// --check: exit 1 when the generated block differs from what the installed DSH would produce.
// Exit 2 = error (source missing, shape changed). Never touches anything outside this bundle.
'use strict'
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')

const PRESETS = ['standard', 'cordis']
const BEGIN = '# >>> GENERATED by tools/sync-presets.cjs — do not edit by hand >>>'
const END = '# <<< GENERATED <<<'
const TOOLS_FILE = path.join(__dirname, 'role-tools.yml')
const PATCH_FILE = path.join(__dirname, '..', 'cordis.patch.yml')

function fail(msg) { console.error('[sync-presets] ' + msg); process.exit(2) }

function locateDsh() {
  const candidates = [process.env.DSH_INSTALL_DIR,
    path.join(process.env.LOCALAPPDATA || '', 'Programs', 'DeepSeek Harness', 'resources', 'app.asar', 'dsh', 'node_modules', '@deepseek-ai', 'dsh')]
  for (const dir of candidates) {
    if (!dir) continue
    try {
      const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'))
      if (pkg.name === '@deepseek-ai/dsh') return { dir, version: pkg.version }
    } catch {}
  }
  fail('installed DSH not found (set DSH_INSTALL_DIR or run with the DSH Electron executable)')
}

function build() {
  const dsh = locateDsh()
  const webApp = path.dirname(require.resolve('@deepseek-ai/dsh-web-app/package.json', { paths: [dsh.dir] }))
  const yaml = require(require.resolve('yaml', { paths: [dsh.dir] }))
  const tools = fs.readFileSync(TOOLS_FILE, 'utf8').replace(/\r/g, '').trimEnd().split('\n')

  const out = [BEGIN, `# Source: @deepseek-ai/dsh ${dsh.version}, dsh-web-app/presets/{${PRESETS.join(',')}}.patch.yml`]
  for (const preset of PRESETS) {
    const src = fs.readFileSync(path.join(webApp, 'presets', `${preset}.patch.yml`), 'utf8').replace(/\r/g, '')
    const sha = crypto.createHash('sha256').update(src).digest('hex')
    const lines = src.split('\n')
    const start = lines.findIndex(l => l === `    - id: preset-${preset}`)
    if (start < 0) fail(`${preset}: row "preset-${preset}" not found — preset file shape changed`)
    // Turn the `- insert:` row into a top-level override row: drop 4 columns of indent.
    const row = lines.slice(start).map(l => l.startsWith('    ') ? l.slice(4) : l.trim() === '' ? '' : null)
    if (row.includes(null)) fail(`${preset}: unexpected indentation after preset row`)
    // Insert the role tools as the last children of the `delegation` group.
    const del = row.findIndex(l => l === '      - id: delegation')
    if (del < 0) fail(`${preset}: delegation group not found`)
    if (row[del + 1] !== '        name: cordis:group') fail(`${preset}: delegation is not a cordis:group`)
    let end = del + 1
    while (end < row.length && (row[end] === '' || /^ {8}/.test(row[end]))) end++
    while (row[end - 1] === '') end--
    row.splice(end, 0, ...tools.map(l => l === '' ? '' : '          ' + l))
    while (row.length && row[row.length - 1] === '') row.pop()
    out.push('', `# preset ${preset}: source sha256 ${sha}`, ...row)
  }
  out.push(END)
  const block = out.join('\n')

  // Validate: parses, and each override carries all four role tools inside delegation.
  const doc = yaml.parseDocument(block, { customTags: [{ tag: '!!js', resolve: s => ({ js: s }) }] })
  if (doc.errors.length) fail('generated YAML invalid: ' + doc.errors.map(e => e.message).join('; '))
  const toolIds = yaml.parse(tools.join('\n')).map(t => t.id)
  for (const r of doc.toJS()) {
    const d = r.config.plugins.find(p => p.id === 'delegation')
    const have = d.config.map(p => p.id)
    for (const id of toolIds) if (!have.includes(id)) fail(`${r.id}: ${id} missing after insertion`)
  }
  return { block, version: dsh.version }
}

const { block, version } = build()
const current = fs.readFileSync(PATCH_FILE, 'utf8').replace(/\r/g, '')
const b = current.indexOf(BEGIN), e = current.indexOf(END)
const existing = b >= 0 && e > b ? current.slice(b, e + END.length) : null

if (existing === block) { console.log(`[sync-presets] up to date with DSH ${version}`); process.exit(0) }
if (process.argv.includes('--check')) {
  console.log(`[sync-presets] DRIFT: generated presets do not match installed DSH ${version}; run without --check`)
  process.exit(1)
}
const next = existing
  ? current.slice(0, b) + block + current.slice(e + END.length)
  : current.trimEnd() + '\n\n' + block + '\n'
fs.writeFileSync(PATCH_FILE, next)
console.log(`[sync-presets] regenerated lead presets (${PRESETS.join(', ')}) from DSH ${version}; open a NEW session to use them`)
