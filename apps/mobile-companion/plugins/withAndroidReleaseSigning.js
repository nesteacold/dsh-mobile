// Config plugin for DSH Orbit — Android RELEASE signing (spec 032, Play upload key).
//
// What it guarantees for `npx expo prebuild --platform android`:
//
//   * `android/app/build.gradle` gains a `signingConfigs.release` block whose four inputs are read
//     from the Gradle properties `DSH_ORBIT_UPLOAD_STORE_FILE`, `DSH_ORBIT_UPLOAD_KEY_ALIAS`,
//     `DSH_ORBIT_UPLOAD_STORE_PASSWORD` and `DSH_ORBIT_UPLOAD_KEY_PASSWORD` — i.e. from the
//     machine's `~/.gradle/gradle.properties`, never from this repository. No keystore path and no
//     password is ever authored here, so a prebuild from a clean checkout cannot carry signing
//     material into git.
//   * `buildTypes.release.signingConfig` points at that config, replacing the
//     prebuild-generated `signingConfig signingConfigs.debug`. That debug default is exactly why
//     Play rejected the previous AAB: the bundle was `bundleRelease`-built but debug-signed.
//   * A missing or empty property FAILS the Gradle build with a message that names the property
//     and the file it belongs in. It does not silently fall back to the debug keystore and it does
//     not produce an unsigned bundle — either would only be discovered at upload time.
//
// Where the values live (owner custody, outside the repo):
//   ~/.android-keys/dsh-orbit-upload.jks        the PKCS12 upload keystore
//   ~/.gradle/gradle.properties                 the four DSH_ORBIT_UPLOAD_* values above
//
// The pure helper `applyReleaseSigning` holds all the logic so it is unit-testable without a
// native project (`test/release-signing.test.ts`); the `with*` wrapper only wires it to prebuild.
//
// Registered in `app.json` `expo.plugins` as `"./plugins/withAndroidReleaseSigning"`.

const { withAppBuildGradle, createRunOncePlugin } = require('expo/config-plugins');

const PLUGIN_NAME = 'dsh-android-release-signing';
const PLUGIN_VERSION = '1.0.0';

/** Gradle properties this config reads. Names only — values never appear in this file. */
const PROPERTY_NAMES = Object.freeze({
  storeFile: 'DSH_ORBIT_UPLOAD_STORE_FILE',
  keyAlias: 'DSH_ORBIT_UPLOAD_KEY_ALIAS',
  storePassword: 'DSH_ORBIT_UPLOAD_STORE_PASSWORD',
  keyPassword: 'DSH_ORBIT_UPLOAD_KEY_PASSWORD',
});

const SIGNCONFIG_NAME = 'release';

/**
 * The Gradle this block is inserted before. Expo's template always declares `buildTypes` after
 * `signingConfigs`, and `signingConfigs.release` must be defined before it is referenced.
 */
const SIGNCONFIG_ANCHOR = 'signingConfigs {';
const BUILD_TYPES_ANCHOR = 'buildTypes {';

/** The prebuild-generated release block; matched so the debug default can be replaced in place. */
const DEBUG_RELEASE_SIGNING = /signingConfig\s+signingConfigs\.debug/;
/** The already-wired form, so a second prebuild is a no-op. */
const RELEASE_SIGNING = /signingConfig\s+signingConfigs\.release/;

function propertyOrFail(name) {
  // `providers.gradleProperty` is the Gradle-8 way to read a build property; it resolves from
  // ~/.gradle/gradle.properties, -P flags and the project's own gradle.properties alike.
  // The message is ONE Groovy string literal: a multi-line concatenation inside
  // `throw new GradleException(...)` does not parse in a build script.
  const message =
    `${name} is not set. DSH Orbit release builds need the upload key: define ${name} in ` +
    '~/.gradle/gradle.properties (owner custody, never in this repo). See ' +
    'apps/mobile-companion/plugins/withAndroidReleaseSigning.js.';
  return [
    `        def __${name} = providers.gradleProperty('${name}').orNull`,
    `        if (__${name} == null || __${name}.trim().isEmpty()) {`,
    `            throw new GradleException('${message}')`,
    '        }',
  ].join('\n');
}

/** The complete `signingConfigs.release` block, indented for insertion inside `signingConfigs`. */
function releaseSigningConfigBlock() {
  return [
    `        // DSH Orbit upload key — generated by plugins/withAndroidReleaseSigning.js.`,
    `        // Values come from ~/.gradle/gradle.properties; nothing secret is authored here.`,
    `        release {`,
    propertyOrFail(PROPERTY_NAMES.storeFile),
    propertyOrFail(PROPERTY_NAMES.keyAlias),
    propertyOrFail(PROPERTY_NAMES.storePassword),
    propertyOrFail(PROPERTY_NAMES.keyPassword),
    `            storeFile file(__${PROPERTY_NAMES.storeFile})`,
    `            storePassword __${PROPERTY_NAMES.storePassword}`,
    `            keyAlias __${PROPERTY_NAMES.keyAlias}`,
    `            keyPassword __${PROPERTY_NAMES.keyPassword}`,
    `        }`,
  ].join('\n');
}

/**
 * Insert (once) `signingConfigs.release` and point `buildTypes.release.signingConfig` at it.
 *
 * Idempotent: a second prebuild over an already-patched file changes nothing. Pure string in /
 * string out so the behaviour is testable without Gradle.
 *
 * @param {string} contents `android/app/build.gradle` as read from disk.
 * @returns {string} the patched contents.
 */
function applyReleaseSigning(contents) {
  if (typeof contents !== 'string') {
    throw new Error(`${PLUGIN_NAME}: expected android/app/build.gradle contents as a string`);
  }
  if (!contents.includes(SIGNCONFIG_ANCHOR)) {
    throw new Error(
      `${PLUGIN_NAME}: android/app/build.gradle has no \`signingConfigs {\` block, so the upload ` +
        'signing config cannot be declared. Re-run `npx expo prebuild --platform android`.',
    );
  }
  if (!contents.includes(BUILD_TYPES_ANCHOR)) {
    throw new Error(
      `${PLUGIN_NAME}: android/app/build.gradle has no \`buildTypes {\` block, so ` +
        '`buildTypes.release.signingConfig` cannot be wired.',
    );
  }

  const alreadyApplied = contents.includes(PROPERTY_NAMES.storeFile);

  let patched = contents;
  if (!alreadyApplied) {
    patched = patched.replace(SIGNCONFIG_ANCHOR, `${SIGNCONFIG_ANCHOR}\n${releaseSigningConfigBlock()}`);
  }

  // Correct the RELEASE build type only — `debug { signingConfig signingConfigs.debug }` must keep
  // the debug key. The scope is the `release { … }` block that sits inside `buildTypes`, found by
  // brace matching so a nested block cannot end the scan early.
  const scoped = rewriteReleaseBuildType(patched);
  if (!scoped.found) {
    throw new Error(
      `${PLUGIN_NAME}: android/app/build.gradle declares no \`buildTypes { release { … } }\` ` +
        'block, so the release signing config cannot be wired.',
    );
  }
  // The guard reads the release block only. `signingConfigs.debug` from the sibling `debug { }`
  // build type must not be able to satisfy it — that is the whole defect this plugin fixes.
  if (!RELEASE_SIGNING.test(scoped.releaseBody)) {
    throw new Error(
      `${PLUGIN_NAME}: the release build type declares no signingConfig to correct; expected ` +
        '`signingConfig signingConfigs.debug` inside `buildTypes { release { … } }`.',
    );
  }
  patched = patched.slice(0, scoped.bodyStart) + scoped.body +
    patched.slice(scoped.bodyStart + scoped.bodyLength);

  return patched;
}

/**
 * Rewrite `buildTypes { ... }` so the release build type points at the release signing config.
 * `body` is the patched `buildTypes` body; `releaseBody` is the rewritten release build type on
 * its own, which is what the caller's guard inspects.
 */
function rewriteReleaseBuildType(contents) {
  const buildTypes = contents.indexOf(BUILD_TYPES_ANCHOR);
  if (buildTypes < 0) {
    return { found: false, body: '', releaseBody: '', bodyStart: 0, bodyLength: 0 };
  }
  const bodyStart = buildTypes + BUILD_TYPES_ANCHOR.length;
  const bodyEnd = matchingBrace(contents, bodyStart - 1);
  if (bodyEnd < 0) return { found: false, body: '', releaseBody: '', bodyStart: 0, bodyLength: 0 };
  const body = contents.slice(bodyStart, bodyEnd);

  const releaseIndex = body.indexOf('release {');
  if (releaseIndex < 0) {
    return { found: false, body, releaseBody: '', bodyStart, bodyLength: bodyEnd - bodyStart };
  }
  const releaseOpen = releaseIndex + 'release '.length;
  const releaseBodyEnd = matchingBrace(body, releaseOpen);
  if (releaseBodyEnd < 0) {
    return { found: false, body, releaseBody: '', bodyStart, bodyLength: bodyEnd - bodyStart };
  }

  const releaseBody = body
    .slice(releaseOpen + 1, releaseBodyEnd)
    .replace(DEBUG_RELEASE_SIGNING, `signingConfig signingConfigs.${SIGNCONFIG_NAME}`);

  const rewritten = body.slice(0, releaseOpen + 1) + releaseBody + body.slice(releaseBodyEnd);

  return { found: true, body: rewritten, releaseBody, bodyStart, bodyLength: bodyEnd - bodyStart };
}

/** Index of the `}` closing the block opened at `openIndex`, or -1. */
function matchingBrace(contents, openIndex) {
  let depth = 0;
  for (let index = openIndex; index < contents.length; index += 1) {
    if (contents[index] === '{') depth += 1;
    else if (contents[index] === '}') {
      depth -= 1;
      if (depth === 0) return index;
    }
  }
  return -1;
}

// ---------------------------------------------------------------------------
// Mod
// ---------------------------------------------------------------------------

const withAndroidReleaseSigning = (config) =>
  withAppBuildGradle(config, (config) => {
    if (config.modResults.language !== 'groovy') {
      throw new Error(
        `${PLUGIN_NAME}: expected a Groovy android/app/build.gradle, got ` +
          `"${config.modResults.language}". This plugin does not rewrite a Kotlin DSL build file.`,
      );
    }
    config.modResults.contents = applyReleaseSigning(config.modResults.contents);
    return config;
  });

// ---------------------------------------------------------------------------
// Entry
// ---------------------------------------------------------------------------

function withAndroidReleaseSigningPlugin(config) {
  return withAndroidReleaseSigning(config);
}

module.exports = createRunOncePlugin(withAndroidReleaseSigningPlugin, PLUGIN_NAME, PLUGIN_VERSION);
module.exports.default = module.exports;
module.exports.withAndroidReleaseSigning = withAndroidReleaseSigningPlugin;
module.exports.applyReleaseSigning = applyReleaseSigning;
module.exports.releaseSigningConfigBlock = releaseSigningConfigBlock;
module.exports.PROPERTY_NAMES = PROPERTY_NAMES;
module.exports.PLUGIN_NAME = PLUGIN_NAME;
module.exports.SIGNCONFIG_NAME = SIGNCONFIG_NAME;
