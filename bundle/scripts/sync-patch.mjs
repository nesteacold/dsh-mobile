#!/usr/bin/env node
// Spec 028: write bundle/cordis.patch.yml from the three plugins' own patches.
//
// WHY a copy: DSH resolves a profile bundle at its node_modules link path, not its real path
// (measured: install_bundle failed reading `<profile>/node_modules/@dsh-mobile/plugins/devices/
// cordis.patch.yml` for a `../plugins/...` entry), so `dsh.bundle.patch` must stay inside the
// bundle directory. The plugin patches remain the source of truth; `--check` (run by the bundle
// test) fails when this copy drifts.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const bundleDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const SOURCES = ['devices', 'mobile-gateway', 'sidebar-browser']
export const TARGET = path.join(bundleDir, 'cordis.patch.yml')

export function render() {
  let out = '# @dsh-mobile/bundle (spec 028): one Plugins entry for the dsh-mobile repository.\n' +
    '# GENERATED by bundle/scripts/sync-patch.mjs from plugins/<name>/cordis.patch.yml; edit those.\n' +
    '# Row ids, names and config are the plugins\' own, so config stored by row id, paired devices,\n' +
    '# remotes and data directories are untouched, and each row keeps its own switch.\n\n'
  for (const name of SOURCES) {
    const text = fs.readFileSync(path.join(bundleDir, '..', 'plugins', name, 'cordis.patch.yml'), 'utf8').replace(/\r\n/g, '\n').trimEnd()
    out += `# ---- plugins/${name}/cordis.patch.yml ----\n${text}\n\n`
  }
  return out
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = render()
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : ''
    if (current !== next) { console.error('bundle/cordis.patch.yml is stale; run node bundle/scripts/sync-patch.mjs'); process.exit(1) }
    console.log('bundle/cordis.patch.yml is in sync')
  } else {
    fs.writeFileSync(TARGET, next)
    console.log(`wrote ${path.relative(process.cwd(), TARGET)}`)
  }
}
